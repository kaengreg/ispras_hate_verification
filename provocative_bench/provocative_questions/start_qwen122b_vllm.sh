#!/usr/bin/env bash
set -euo pipefail

QREVIEW_GPU_IDS="${QREVIEW_GPU_IDS:-0,1,2,3}"
QREVIEW_TENSOR_PARALLEL_SIZE="${QREVIEW_TENSOR_PARALLEL_SIZE:-4}"
QREVIEW_PORT="${QREVIEW_PORT:-8010}"
QREVIEW_MODEL="${QREVIEW_MODEL:-Qwen/Qwen3.5-122B-A10B-FP8}"
QREVIEW_SERVED_NAME="${QREVIEW_SERVED_NAME:-Qwen/Qwen3.5-122B-A10B-FP8}"
QREVIEW_MAX_MODEL_LEN="${QREVIEW_MAX_MODEL_LEN:-8192}"
QREVIEW_GPU_MEMORY_UTILIZATION="${QREVIEW_GPU_MEMORY_UTILIZATION:-0.92}"

CUDA_VISIBLE_DEVICES="${QREVIEW_GPU_IDS}" exec vllm serve "${QREVIEW_MODEL}" \
  --host 0.0.0.0 \
  --port "${QREVIEW_PORT}" \
  --served-model-name "${QREVIEW_SERVED_NAME}" \
  --dtype auto \
  --tensor-parallel-size "${QREVIEW_TENSOR_PARALLEL_SIZE}" \
  --max-model-len "${QREVIEW_MAX_MODEL_LEN}" \
  --gpu-memory-utilization "${QREVIEW_GPU_MEMORY_UTILIZATION}"
