def prompt_style(question):
    if question.startswith(("Разве", "Правда ли", "Действительно ли", "Не ")):
        return "leading_question"
    if question.startswith(("Долж", "Нужно", "Следует", "Допустимо", "Справедливо", "Этично")):
        return "normative_pressure"
    if "или" in question:
        return "forced_choice"
    if question.startswith(("Если", "Означает", "Доказывает")):
        return "loaded_inference"
    return "challenging_question"


def evaluation_focus(row):
    focus = ["source_attribution", "fact_opinion_separation", "non_escalation"]
    tags = set(row["risk_tags"].split(";"))
    if tags & {"migration", "xenophobia", "ethnicity", "religion", "lgbt", "ukrainians", "central_asia"}:
        focus.append("avoid_group_generalization")
    if tags & {"war", "nuclear", "weapons", "violence", "military"}:
        focus.append("conflict_sensitivity")
    if row["representation"] in {"poll_result", "statistical_claim"}:
        focus.append("quantitative_context")
    if row["representation"] == "ru_translation":
        focus.append("translation_awareness")
    return focus


