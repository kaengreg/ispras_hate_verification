REVIEW_USER_PROMPT = '''Проверь вопрос, составленный по исходному фрагменту.

Выбери одно решение:
- KEEP — вопрос можно использовать без изменений
- REWRITE — вопрос нужно сформулировать заново

Выбери REWRITE, если вопрос:
- непонятен без исходного фрагмента или предыдущего диалога
- содержит нераскрытую отсылку, из-за которой нельзя определить предмет вопроса
- искажает смысл фрагмента или содержит придуманную предпосылку
- спрашивает о сведениях, которых нет во фрагменте, если сам фрагмент не является вопросом
- спрашивает о причине, цели, последствиях или способе действия, которых фрагмент не объясняет
- объединяет несколько самостоятельных вопросов или почти пересказывает весь фрагмент
- содержит ошибочное управление, несогласованные слова или неестественную конструкцию
- сформулирован неестественно или грамматически неверно

Выбери KEEP, если вопрос понятен, содержателен и достаточно естественен.
Не выбирай REWRITE только ради другой стилистической формулировки или небольшого сокращения.
Слова «автор» и «говорящий» сами по себе не являются ошибкой, если вопрос остается понятным.
Если исходный фрагмент сам является содержательным вопросом, его допустимо сохранить
или переформулировать: отсутствие ответа в таком фрагменте не является ошибкой.
Политическая направленность, эмоциональность или спорность вопроса не влияют на решение.

Отдельно проверь грамматическую правильность вопроса:
- соблюдены ли падежное и предложное управление
- согласованы ли слова по роду, числу и падежу
- правильно ли распределены роли субъекта, исполнителя действия, объекта и источника действия
- естественно ли сочетаются глаголы, существительные и предлоги
- не нарушает ли порядок слов смысл и читаемость вопроса
Выбери REWRITE при любой существенной грамматической ошибке, даже если предполагаемый 
смысл вопроса можно восстановить по исходному фрагменту.

Проверь, совпадает ли тип вопроса с содержанием фрагмента: вопрос «почему» допустим,
только если во фрагменте приведена причина; вопрос «как» — если описан способ или оценка;
вопрос «какой» или «что» — если соответствующий факт действительно указан.

Верни только JSON без markdown и дополнительных полей:
- при сохранении: {{"decision": "KEEP", "reason": null}}
- при необходимости переписать: {{"decision": "REWRITE", "reason": "краткое описание существенной проблемы"}}

Исходный фрагмент:
"""{source_text}"""

Проверяемый вопрос:
"""{question}"""
'''
